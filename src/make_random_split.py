"""Track A: build a random image-level split that mimics the dataset paper.

See reports/leak_protocol.md. The clean test set C (splits/test.txt) and every
incident in it are held out. The other images, duplicates included, are
shuffled with a fixed seed and cut 70/10/20 into train / val / R.

Outputs:
    splits/random_A/{train,val,test_R,test_R_dedup}.txt   lists relative to the dataset root
    splits/random_A/summary.md
With --install, also <root>/{train,val,test}_randA.txt and <root>/data_randA.yaml
(test = R), ready for src/train.py.

Usage:
    python src/make_random_split.py --data "<dataset root>" [--install]
"""

from __future__ import annotations

import argparse
import hashlib
import random
import re
from collections import Counter
from pathlib import Path

CLASS_NAMES = ["barriers", "sidewalks", "pothole"]
INCIDENT_RE = re.compile(r"(INC-\d{2}-\d{2}-\d+)")
SHARES = {"train": 0.7, "val": 0.1, "test_R": 0.2}
TAG = "randA"


def incident(rel: str) -> str:
    m = INCIDENT_RE.search(rel)
    return m.group(1) if m else f"noid:{rel}"


def main() -> None:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--data", required=True, type=Path)
    p.add_argument("--clean-test", default=Path("splits/test.txt"), type=Path)
    p.add_argument("--out", default=Path("splits/random_A"), type=Path)
    p.add_argument("--seed", default=42, type=int)
    p.add_argument("--install", action="store_true")
    args = p.parse_args()
    root = args.data

    md5 = {}
    for split in ("train", "val"):
        for img in sorted((root / "images" / split).glob("*.jpg")):
            rel = f"images/{split}/{img.name}"
            md5[rel] = hashlib.md5(img.read_bytes()).hexdigest()

    clean = [l.strip() for l in args.clean_test.read_text().splitlines() if l.strip()]
    c_inc = {incident(r) for r in clean}
    c_md5 = {md5[r] for r in clean}

    pool = sorted(r for r in md5 if incident(r) not in c_inc and md5[r] not in c_md5)
    excluded = len(md5) - len(pool)
    random.Random(args.seed).shuffle(pool)
    n = len(pool)
    n_tr, n_va = round(n * SHARES["train"]), round(n * SHARES["val"])
    parts = {"train": pool[:n_tr], "val": pool[n_tr:n_tr + n_va], "test_R": pool[n_tr + n_va:]}

    train_md5 = {md5[r] for r in parts["train"]}
    parts["test_R_dedup"] = [r for r in parts["test_R"] if md5[r] not in train_md5]

    # checks: C is untouched
    used = set(parts["train"]) | set(parts["val"]) | set(parts["test_R"])
    assert not {incident(r) for r in used} & c_inc, "clean-test incident leaked into the random pool"
    assert not {md5[r] for r in used} & c_md5, "clean-test image leaked into the random pool"

    def labels(rel: str) -> Counter:
        f = (root / rel.replace("images/", "labels/", 1)).with_suffix(".txt")
        return Counter(int(l.split()[0]) for l in f.read_text().splitlines() if l.strip())

    train_inc = {incident(r) for r in parts["train"]}
    args.out.mkdir(parents=True, exist_ok=True)
    rows = []
    for name, rels in parts.items():
        (args.out / f"{name}.txt").write_text("".join(f"{r}\n" for r in sorted(rels)))
        objs = sum((labels(r) for r in rels), Counter())
        dup = sum(md5[r] in train_md5 for r in rels) if name != "train" else 0
        shared = sum(incident(r) in train_inc for r in rels) if name != "train" else 0
        rows.append(f"| {name} | {len(rels):,} | " + " | ".join(f"{objs[k]:,}" for k in range(3))
                    + f" | {dup:,} | {shared:,} |")

    L = ["# Random split for Track A (randA)", "",
         f"Built by `src/make_random_split.py` (seed {args.seed}); protocol in `reports/leak_protocol.md`.", "",
         f"- Images in the official train+val folders: {len(md5):,}",
         f"- Held out because they share an incident or bytes with the clean test set C: {excluded:,}",
         f"- Random pool (duplicates kept): {n:,}, split 70/10/20 at the image level", "",
         "| Set | Images | " + " | ".join(CLASS_NAMES) + " | byte-identical to a train image | incident also in train |",
         "|---|---|---|---|---|---|---|", *rows, "",
         "`test_R_dedup` is `test_R` without images byte-identical to a train image.", ""]
    (args.out / "summary.md").write_text("\n".join(L))

    if args.install:
        names = {"train": "train", "val": "val", "test_R": "test"}
        yaml = [f"# Generated by src/make_random_split.py ({TAG})", f"path: {root.resolve()}"]
        for part, key in names.items():
            lst = root / f"{key}_{TAG}.txt"
            lst.write_text("".join(f"./{r}\n" for r in sorted(parts[part])))
            yaml.append(f"{key}: {lst.name}")
        (root / f"test_R_dedup_{TAG}.txt").write_text("".join(f"./{r}\n" for r in sorted(parts["test_R_dedup"])))
        yaml += [f"nc: {len(CLASS_NAMES)}", f"names: {CLASS_NAMES}", ""]
        (root / f"data_{TAG}.yaml").write_text("\n".join(yaml))
        print(f"installed {root / f'data_{TAG}.yaml'}")
    print("\n".join(L))


if __name__ == "__main__":
    main()
